const stopWords = new Set([
  "make",
  "new",
  "message",
  "for",
  "my",
  "wife",
  "husband",
  "lover",
  "love",
  "long",
  "short",
  "sweet",
  "romantic",
  "deep",
  "please",
  "write",
  "create",
  "generate",
  "good",
  "morning",
  "night",
]);

function seededPick(list, seed) {
  return list[Math.abs(seed) % list.length];
}

function extractNames(namesLabel) {
  const [firstName = "Ali", secondName = "Mahi"] = namesLabel
    .split("+")
    .map((item) => item.trim())
    .filter(Boolean);

  return {
    senderName: firstName || "Ali",
    loverName: secondName || "Mahi",
  };
}

function extractRequestedName(searchTerm, fallbackName) {
  const words = (searchTerm.match(/[A-Za-z]{3,}/g) || []).filter(
    (word) => !stopWords.has(word.toLowerCase())
  );

  const preferredWord = words.find((word) => word === word.toUpperCase()) || words[0];

  if (!preferredWord) {
    return fallbackName;
  }

  return preferredWord.charAt(0).toUpperCase() + preferredWord.slice(1).toLowerCase();
}

function buildPromptMood(searchTerm, recipientName) {
  const normalized = searchTerm.toLowerCase();
  const lines = [];

  if (normalized.includes("wife")) {
    lines.push(
      `${recipientName}, loving you as my wife feels like finding peace, loyalty, warmth, and home in one beautiful person.`
    );
  }

  if (normalized.includes("miss")) {
    lines.push(
      `Even when distance stretches the day, my heart keeps moving toward you because missing you only reminds me how deeply I love you.`
    );
  }

  if (normalized.includes("sorry") || normalized.includes("apolog")) {
    lines.push(
      `If my words or actions ever hurt you, I want you to know that I carry that regret honestly and I still want to love you more gently and carefully.`
    );
  }

  if (normalized.includes("good morning")) {
    lines.push(
      `Every morning feels softer when I imagine your smile, and I want your day to begin with the same sweetness you bring into my life.`
    );
  }

  if (normalized.includes("good night")) {
    lines.push(
      `Before the night becomes quiet, I want my love to reach you and remind you that you are the calmest thought in my heart.`
    );
  }

  if (normalized.includes("forever") || normalized.includes("marriage")) {
    lines.push(
      `When I think about forever, I do not think about time alone, I think about a life where love stays respectful, loyal, soft, and beautifully true.`
    );
  }

  if (normalized.includes("long distance")) {
    lines.push(
      `No matter how many miles stand between us, they can never measure the closeness I feel to you inside my heart.`
    );
  }

  if (!lines.length) {
    lines.push(
      `The feeling behind your request matters to me because every loving message should sound personal, gentle, emotional, and true to the heart.`
    );
  }

  return lines.join(" ");
}

export function createAiStyleLoveMessage(
  searchTerm = "",
  namesLabel = "KHADIJA + SHAHZAIB",
  variationSeed = 0
) {
  const { senderName, loverName } = extractNames(namesLabel);
  const recipientName = extractRequestedName(searchTerm, loverName);
  const normalized = searchTerm.trim();
  const seedBase = normalized.length + variationSeed * 7;
  const intro = seededPick(
    [
      `My dearest ${recipientName}, there are moments when I try to write a simple message for you, but my heart refuses to stay small because what I feel is much deeper than a few ordinary words.`,
      `${recipientName}, every time I think about you, my feelings become longer than the message I planned to write, because your place in my heart has grown into something truly beautiful and unforgettable.`,
      `To my beloved ${recipientName}, I wanted to send just one sweet message, but your love always turns a few lines into a full confession of how much you mean to me.`,
      `${recipientName}, if I could let you see my heart while I write this, you would understand why every message for you becomes emotional, sincere, and full of affection.`,
    ],
    seedBase
  );
  const middle = seededPick(
    [
      `You are the kind of person who makes love feel peaceful instead of confusing, safe instead of uncertain, and meaningful instead of temporary.`,
      `Being connected to you has changed the way I understand love, because now I know it can be soft, loyal, patient, and still incredibly powerful.`,
      `What I feel for you is not a passing emotion. It is a steady, growing attachment that keeps returning to your name with warmth, gratitude, and tenderness.`,
      `Your love has become part of the rhythm of my life, and even in quiet moments I can feel how much comfort and light you bring into my world.`,
    ],
    seedBase + 1
  );
  const promise = seededPick(
    [
      `I want to keep choosing you with honesty, to keep protecting your feelings, and to keep building memories that feel beautiful even years from now.`,
      `I promise to keep loving you with patience, to keep remembering the little things, and to keep showing you that sincere love still exists.`,
      `I want my love for you to feel dependable, calm, and real, so that whenever you think of me, your heart feels safe rather than uncertain.`,
      `I promise to stay careful with your heart, because what we share deserves tenderness, respect, and a future filled with genuine care.`,
    ],
    seedBase + 2
  );
  const closing = seededPick(
    [
      `So if you ever wonder what you mean to me, remember this: you are loved deeply, remembered often, and treasured in a way that words can only partially explain.`,
      `That is why no matter how long this message becomes, it still feels shorter than the truth, because the truth is that loving you has become one of the best parts of my life.`,
      `And if this message reaches your heart the way your love reaches mine, then maybe you will understand why I never get tired of choosing you again and again.`,
      `So I hope you keep this message close, because it carries a simple truth that will not change: my heart holds your name with softness, loyalty, and real affection.`,
    ],
    seedBase + 3
  );
  const requestLine = normalized
    ? `When I read your request, "${normalized}", I wanted this message to sound exactly the way a real heart would speak when love becomes too full to hide.`
    : `Even without a detailed prompt, my heart still leans toward the softest truth I know: love becomes more beautiful when it is honest, personal, and patiently expressed.`;
  const moodLine = buildPromptMood(normalized, recipientName);

  return `${intro}\n\n${requestLine} ${middle} ${moodLine}\n\n${senderName} wants you to know that your presence is not small in this life. You are part of the thoughts that stay after midnight, the memories that return during quiet afternoons, and the hopes that make the future feel warm instead of empty. ${promise}\n\n${closing}`;
}
